let lang: UiLang = readInitial()

function readInitial(): UiLang {
  try {
    return localStorage.getItem(STORAGE_KEY) === 'ug' ? 'ug' : 'zh'
  } catch {
    return 'zh'
  }
}

function applyUiLang(next: UiLang): void {
  lang = next
  if (typeof document !== 'undefined') {
    document.documentElement.lang = next === 'ug' ? 'ug' : 'zh-CN'
    document.documentElement.dir = next === 'ug' ? 'rtl' : 'ltr'
  }
  try {
    localStorage.setItem(STORAGE_KEY, next)
  } catch {
    /* 忽略存储异常 */
  }
}

applyUiLang(readInitial())

export function getUiLang(): UiLang {
  return lang
}

export function setUiLang(next: UiLang): void {
  if (next === lang) return
  applyUiLang(next)
  listeners.forEach((listener) => listener())
}

export function useUiLang(): UiLang {
  return useSyncExternalStore(
    (listener) => {
      listeners.add(listener)
      return () => listeners.delete(listener)
    },
    getUiLang,
  )
}

export function t(key: string, params?: Record<string, string | number>): string {
  const dict = lang === 'ug' ? ug : zh
  let text = dict[key] ?? zh[key] ?? key
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replace(`{${name}}`, String(value))
    }
  }
  return text
}